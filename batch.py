def load_prompts(args: argparse.Namespace) -> list[str]:
    if args.prompts:
        lines = [l.strip() for l in Path(args.prompts).read_text(encoding="utf-8").splitlines()]
        prompts = [l for l in lines if l and not l.startswith("#")]
        if not prompts:
            sys.exit(f"no prompts in {args.prompts}")
        return prompts
    key = args.category.strip().lower()
    if key not in PROMPT_SETS:
        sys.exit(f"no built-in prompt set for '{args.category}'; pass --prompts file.txt (built-in: {', '.join(PROMPT_SETS)})")
    return PROMPT_SETS[key]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--category", default="Nature", help="category name: output folder outputs/<category>/ and db category")
    ap.add_argument("--count", type=int, default=50)
    ap.add_argument("--model", default="zimage", help="model key, or 'auto'")
    ap.add_argument("--prompts", help="text file with one prompt per line (overrides the built-in set)")
    ap.add_argument("--seed-start", type=int, default=None, help="first seed; later images use seed+1, +2 ... (default: random)")
    ap.add_argument("--skip", type=int, default=0, help="start at this prompt index (to resume a batch)")
    ap.add_argument("--negative", default="")
    ap.add_argument("--url", default="http://127.0.0.1:7860")
    ap.add_argument("--list", action="store_true", help="print the built-in prompt sets and exit")
    args = ap.parse_args()

    if args.list:
        for name, ps in PROMPT_SETS.items():
            print(f"{name}: {len(ps)} prompts")
            for p in ps:
                print("  ", p)
        return

    prompts = load_prompts(args)
    try:
        from gradio_client import Client
        client = Client(args.url, verbose=False)
    except Exception as e:
        sys.exit(f"The app is not reachable at {args.url} ({e}). Start it with  .venv\\Scripts\\python.exe app.py  and run again.")

    seed = args.seed_start if args.seed_start is not None else random.randint(1, 10_000_000)
    print(f"Generating {args.count} images for category '{args.category}' with model '{args.model}' through {args.url}")
    done, failed, t_all = 0, 0, time.time()
    for i in range(args.count):
        base = prompts[(args.skip + i) % len(prompts)]
        prompt = f"{base}, seed {seed + i}"
        t0 = time.time()
        try:
            result = client.predict(prompt, args.negative, args.model, [], args.category, api_name="/generate")
            report = result[1]
            line = next((l for l in report.splitlines() if l.startswith("- Inference")), "")
            m = re.search(r"Generation #(\d+)", report)
            gen_id = m.group(1) if m else "?"
            done += 1
            print(f"[{i + 1:>3}/{args.count}] #{gen_id} {time.time() - t0:5.1f}s  {line.replace('- ', '')}  | {base[:70]}", flush=True)
        except Exception as e:
            failed += 1
            print(f"[{i + 1:>3}/{args.count}] FAILED {str(e)[:160]}  | {base[:70]}", flush=True)
    mins = (time.time() - t_all) / 60
    print(f"\n{done} images saved to outputs/{args.category}/ in {mins:.1f} min ({failed} failed). "
          f"Prompts are in the database:  python db.py prompts {args.category}")


if __name__ == "__main__":
    main()
